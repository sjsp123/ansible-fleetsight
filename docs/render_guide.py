#!/usr/bin/env python3
"""
Regenerates roles/linuxdb_dashboard/files/guide_content.html from
OPERATIONAL_SUPPORT_GUIDE.md.

This is a BUILD-TIME tool only - it runs here in the repo, never on a
target host, and its output is a plain static file checked into the
repo like any other role file. roles/linuxdb_dashboard/tasks/main.yml
just copies that already-generated HTML to the dashboard host; the
dashboard itself (app.py) never runs markdown conversion or imports
the `markdown` package - it only reads the pre-rendered HTML file at
startup (see GUIDE_HTML / render_guide() in app.py). That keeps the
dashboard's own dependency footprint at "python3 standard library
only" (see that role's README).

Usage (from the repo root, after editing OPERATIONAL_SUPPORT_GUIDE.md):

    python3 -m venv /tmp/render_guide_venv          # first time only
    /tmp/render_guide_venv/bin/pip install markdown  # first time only
    /tmp/render_guide_venv/bin/python3 docs/render_guide.py

Or, if the `markdown` package is already available on your machine:

    python3 docs/render_guide.py

Then commit the regenerated roles/linuxdb_dashboard/files/guide_content.html
alongside your OPERATIONAL_SUPPORT_GUIDE.md change, and redeploy
roles/linuxdb_dashboard as usual (the copy task picks up the new file
and restarts the service).

Forgetting to re-render is easy to do, so two guards exist:

  - .githooks/pre-commit (activate per clone with
    `git config core.hooksPath .githooks`) re-runs this script on every
    commit and rejects the commit if the committed HTML was stale.
  - The output carries a "Guide rendered <date>" footer, so staleness
    is visible on the /guide page itself.
"""

import os
import sys
import time

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE_MD = os.path.join(REPO_ROOT, "OPERATIONAL_SUPPORT_GUIDE.md")
OUTPUT_HTML = os.path.join(
    REPO_ROOT, "roles", "linuxdb_dashboard", "files", "guide_content.html"
)


def main():
    try:
        import markdown
    except ImportError:
        sys.stderr.write(
            "error: the 'markdown' Python package isn't installed.\n"
            "Install it first, e.g.:\n"
            "  python3 -m venv /tmp/render_guide_venv\n"
            "  /tmp/render_guide_venv/bin/pip install markdown\n"
            "  /tmp/render_guide_venv/bin/python3 docs/render_guide.py\n"
        )
        return 1

    if not os.path.isfile(SOURCE_MD):
        sys.stderr.write("error: %s not found\n" % SOURCE_MD)
        return 1

    with open(SOURCE_MD, "r", encoding="utf-8") as fh:
        source = fh.read()

    # extra: tables, fenced code blocks (```), etc.
    # toc: assigns each heading a GitHub-style id="..." slug, so the
    #   guide's own internal links (e.g. "#monitoring-alerting") keep
    #   working when served as a static page, exactly as they do when
    #   read as plain markdown (e.g. on GitHub).
    # sane_lists: consistent ordered/unordered list handling.
    html_body = markdown.markdown(
        source, extensions=["extra", "toc", "sane_lists"]
    )

    header = (
        "<!-- AUTO-GENERATED by docs/render_guide.py from "
        "OPERATIONAL_SUPPORT_GUIDE.md - do not hand-edit, your changes "
        "will be overwritten the next time this is regenerated. Edit "
        "the .md source instead, then re-run docs/render_guide.py. -->\n"
    )

    # Build-time freshness stamp, shown at the bottom of /guide. Makes
    # staleness visible in the browser instead of something you only
    # notice when content you know was merged isn't there yet.
    footer = (
        '<hr>\n<p class="guide-footer">Guide rendered %s from '
        "OPERATIONAL_SUPPORT_GUIDE.md by docs/render_guide.py. "
        "If this looks out of date, the .md source was probably edited "
        "without re-rendering this file.</p>\n"
        % time.strftime("%Y-%m-%d %H:%M %Z")
    )

    with open(OUTPUT_HTML, "w", encoding="utf-8") as fh:
        fh.write(header)
        fh.write(html_body)
        fh.write(footer)
        fh.write("\n")

    print("Wrote %s (%d bytes)" % (OUTPUT_HTML, os.path.getsize(OUTPUT_HTML)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
